-- Replayr accounts (Cloudflare D1 / SQLite). Applied automatically by the deploy workflow, or with:
--   npx wrangler d1 execute replayr --remote --file=schema.sql
CREATE TABLE IF NOT EXISTS users (
  id            TEXT PRIMARY KEY,           -- random id
  username      TEXT NOT NULL UNIQUE COLLATE NOCASE,
  pass_hash     TEXT NOT NULL,              -- PBKDF2-SHA256
  pass_salt     TEXT NOT NULL,
  display_name  TEXT NOT NULL,
  quota_bytes   INTEGER NOT NULL DEFAULT 524288000,   -- 500 MB per user (when cloud clips are on)
  used_bytes    INTEGER NOT NULL DEFAULT 0,
  created_at    INTEGER NOT NULL,
  banned        INTEGER NOT NULL DEFAULT 0
);

-- Invite codes: generated by the owner at /admin; each makes exactly one account.
CREATE TABLE IF NOT EXISTS invite_codes (
  code          TEXT PRIMARY KEY,           -- stored without dashes, upper case
  note          TEXT,
  created_at    INTEGER NOT NULL,
  used_by       TEXT,                       -- user id once used
  used_at       INTEGER
);

CREATE TABLE IF NOT EXISTS sessions (
  refresh_hash  TEXT PRIMARY KEY,           -- SHA-256 of the refresh token; the token itself is never stored
  user_id       TEXT NOT NULL,
  device        TEXT,
  created_at    INTEGER NOT NULL,
  last_used_at  INTEGER NOT NULL,
  expires_at    INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_user ON sessions (user_id);

CREATE TABLE IF NOT EXISTS clips (
  id            TEXT PRIMARY KEY,           -- short id used in share links
  user_id       TEXT NOT NULL,
  title         TEXT NOT NULL,
  privacy       TEXT NOT NULL DEFAULT 'unlisted',   -- 'public' | 'unlisted' | 'private'
  size_bytes    INTEGER NOT NULL,
  duration      REAL NOT NULL DEFAULT 0,
  status        TEXT NOT NULL DEFAULT 'uploading',  -- 'uploading' | 'ready' | 'removed'
  views         INTEGER NOT NULL DEFAULT 0,
  created_at    INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS clips_user ON clips (user_id, created_at);

CREATE TABLE IF NOT EXISTS reports (
  id            INTEGER PRIMARY KEY AUTOINCREMENT,
  clip_id       TEXT NOT NULL,
  reason        TEXT NOT NULL,
  created_at    INTEGER NOT NULL,
  ip_hash       TEXT
);
